"""Build the risk_list seed migration from the two public AI risk sources.

  IBM AI Risk Atlas (Apache-2.0)  github.com/IBM/ai-atlas-nexus  risk_atlas_data.yaml
  MIT AI Risk Repository (CC BY 4.0)  airisk.mit.edu  "AI Risk Database v4" sheet

Names, descriptions, categories and links come verbatim from the sources.
Neither source rates severity or likelihood, so those are SUGGESTED defaults set
by the documented rules below (shown as such in the UI); users can change them.

Usage (needs pyyaml + openpyxl):
  python3 build_risk_catalog.py risk_atlas_data.yaml mit.xlsx > ../../drizzle/00NN_risk_catalog_seed.sql
To refresh later: download both files again and write a new numbered migration;
the inserts upsert on (source, source_id), so users' own risks are never touched.
"""

import sys

import openpyxl
import yaml

# ponytail: rule-based defaults by category, refine per risk if a reviewer wants to.
IBM_SEVERITY = {  # by IBM risk group
    "Privacy": "Major", "Data laws": "Major", "Legal compliance": "Major",
    "Intellectual property": "Major", "Fairness": "Major", "Misuse": "Major",
    "Robustness": "Major", "Robustness: prompt attacks": "Major",
    "Robustness: model behavior manipulation": "Major", "Value alignment": "Major",
}  # everything else: Moderate
MIT_SEVERITY = {  # by MIT domain number
    "1": "Major", "2": "Major", "4": "Major", "7": "Major",
}  # 3 Misinformation, 5 Human-computer interaction, 6 Socioeconomic, uncoded: Moderate


def ibm_likelihood(descriptors):
    # Risks IBM marks "specific to" generative/agentic AI arise in normal use of those systems.
    return "Likely" if any(d.startswith("specific to") for d in descriptors) else "Possible"


def mit_likelihood(timing):
    # Post-deployment risks occur while the system is in use; the rest are less direct.
    return "Likely" if (timing or "").startswith("2") else "Possible"


def q(v):
    return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"


def arr(items):
    items = [i for i in items if i]
    return "ARRAY[" + ",".join(q(i) for i in items) + "]::text[]" if items else "ARRAY[]::text[]"


def ibm_rows(path):
    d = yaml.safe_load(open(path))
    groups = {g["id"]: g["name"] for g in d["groups"]}
    for e in d["entries"]:
        group = groups[e["isPartOf"]]
        yield (
            "ibm", e["id"], e["name"].strip(), " ".join(e["description"].split()),
            IBM_SEVERITY.get(group, "Moderate"), ibm_likelihood(e.get("descriptor", [])),
            [group], e.get("url"),
        )


def mit_rows(path):
    ws = openpyxl.load_workbook(path, read_only=True)["AI Risk Database v4"]
    for r in list(ws.iter_rows(values_only=True))[3:]:
        title, quickref, ev_id, paper, cat, sub, _, level, category, subcategory, desc = r[:11]
        timing, domain, subdomain = r[16], r[17], r[18]
        if level not in ("Risk Category", "Risk Sub-Category") or not desc:
            continue
        # Ev_ID is a sheet formula on most rows, a literal on newer ones.
        source_id = (
            ev_id if ev_id and not str(ev_id).startswith("=")
            else f"{int(paper):02d}.{int(cat):02d}.{int(sub or 0):02d}"
        )
        if subcategory in (None, "-", ""):
            subcategory = None
        domain_no = (domain or "").split(".")[0]
        yield (
            "mit", source_id, (subcategory or category).strip(), " ".join(str(desc).split()),
            MIT_SEVERITY.get(domain_no, "Moderate"), mit_likelihood(timing),
            [domain, subdomain if subdomain and subdomain != "X.1 > Excluded" else None],
            f"{quickref} - {title}",
        )


def main(ibm_path, mit_path):
    rows, seen = [], {}
    for r in list(ibm_rows(ibm_path)) + list(mit_rows(mit_path)):
        n = seen[(r[0], r[1])] = seen.get((r[0], r[1]), 0) + 1
        # A few MIT rows share an Ev_ID in the source sheet; keep both, suffix the repeat.
        rows.append(r if n == 1 else (r[0], f"{r[1]}-{n}", *r[2:]))
    keys = [(r[0], r[1]) for r in rows]
    assert len(keys) == len(set(keys)), "duplicate source ids"
    print("-- Generated by scripts/risk-catalog/build_risk_catalog.py. Do not edit by hand.")
    print("-- IBM AI Risk Atlas (Apache-2.0), MIT AI Risk Repository v4 (CC BY 4.0).")
    print("INSERT INTO risk_list (source, source_id, risk_name, description, severity, likelihood, category, source_ref) VALUES")
    print(",\n".join(
        f"({q(src)},{q(sid)},{q(name)},{q(desc)},{q(sev)},{q(lik)},{arr(cats)},{q(ref)})"
        for src, sid, name, desc, sev, lik, cats, ref in rows
    ))
    # Severity/likelihood are not overwritten on refresh, so later tuning survives.
    print("ON CONFLICT (source, source_id) DO UPDATE SET risk_name = EXCLUDED.risk_name, "
          "description = EXCLUDED.description, category = EXCLUDED.category, source_ref = EXCLUDED.source_ref;")
    print(f"-- {sum(k[0] == 'ibm' for k in keys)} IBM + {sum(k[0] == 'mit' for k in keys)} MIT", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
