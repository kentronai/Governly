#!/usr/bin/env bash
# Governly installer: self-host the whole stack with Docker Compose.
#
#   curl -fsSL https://raw.githubusercontent.com/kentronai/Norix/main/install.sh | bash
#   ./install.sh            # from a clone
#   ./install.sh --doctor   # check prerequisites and running services
#
# Settings (environment variables, all optional):
#   GOVERNLY_DIR        where to clone when run via curl      (default: ~/governly)
#   GOVERNLY_REPO       git URL to clone                       (default: kentronai/Norix on GitHub)
#   GOVERNLY_URL        public URL people open                 (default: http://localhost[:port])
#   GOVERNLY_HTTP_PORT  host port nginx listens on             (default: 80)
#   NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY, CLERK_SECRET_KEY      skip the Clerk prompts
#
# Re-running is safe: an existing .env is kept, never overwritten.
set -euo pipefail

GOVERNLY_REPO="${GOVERNLY_REPO:-https://github.com/kentronai/Norix.git}"
GOVERNLY_DIR="${GOVERNLY_DIR:-$HOME/governly}"
GOVERNLY_HTTP_PORT="${GOVERNLY_HTTP_PORT:-80}"   # first install only; afterwards .env holds it

say()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m ok\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m  !\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

check_prereqs() {
  local fail=0
  for bin in git openssl docker; do
    if command -v "$bin" >/dev/null 2>&1; then ok "$bin found"; else warn "$bin is not installed"; fail=1; fi
  done
  if docker compose version >/dev/null 2>&1; then
    # deploy/compose.selfhost.yml uses `!override`, added in Compose 2.24.
    local v; v="$(docker compose version --short 2>/dev/null | sed 's/^v//')"
    if [ "$(printf '%s\n2.24.0\n' "$v" | sort -V | head -1)" = "2.24.0" ]; then ok "docker compose $v"
    else warn "docker compose $v is older than 2.24, please upgrade Docker"; fail=1; fi
  else
    warn "docker compose v2 plugin is missing"; fail=1
  fi
  if docker info >/dev/null 2>&1; then ok "Docker daemon is running"; else warn "Docker daemon is not running (start Docker, then re-run)"; fail=1; fi
  return $fail
}

ask() { # ask VAR "prompt": read from the terminal even under `curl | bash`.
  local __var=$1 __prompt=$2 __val="${!1:-}"
  if [ -z "$__val" ]; then
    [ -r /dev/tty ] || die "$__var is required. Set it in the environment and re-run."
    read -r -p "$__prompt: " __val </dev/tty
  fi
  [ -n "$__val" ] || die "$__var is required."
  printf -v "$__var" '%s' "$__val"
}

b64key() { openssl rand -base64 32; }
uuid()   { local h; h="$(openssl rand -hex 16)"; echo "${h:0:8}-${h:8:4}-4${h:13:3}-a${h:17:3}-${h:20:12}"; }

write_env() {
  local url="$1"
  say "Creating .env (secrets are generated locally and never leave this machine)"
  echo "    Governly signs people in with Clerk. Create a free app at https://dashboard.clerk.com"
  echo "    and copy the two keys from API Keys. (docs/self-hosting.md#clerk explains each step)"
  ask NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY "Clerk publishable key (pk_...)"
  ask CLERK_SECRET_KEY "Clerk secret key (sk_...)"
  # The publishable key is pk_<env>_<base64("<frontend-api-host>$")>.
  local clerk_fapi
  clerk_fapi="$(printf '%s' "${NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY#pk_*_}" | openssl base64 -d -A 2>/dev/null | tr -d '$' || true)"
  local pg; pg="$(openssl rand -hex 24)"
  umask 077
  cat > .env <<EOF
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Reference: docs/configuration.md
GOVERNLY_HTTP_PORT=${GOVERNLY_HTTP_PORT}
NEXT_PUBLIC_APP_ENV=production
NEXT_PUBLIC_APP_URL=${url}
NEXT_PUBLIC_API_URL=${url}
NEXT_PUBLIC_BACKEND_URL=${url}

# Database and cache (compose services)
POSTGRES_PASSWORD=${pg}
DATABASE_URL=postgresql://postgres:${pg}@postgres:5432/ai_governance
REDIS_URL=redis://redis:6379

# Clerk (sign-in)
NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY=${NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY}
CLERK_SECRET_KEY=${CLERK_SECRET_KEY}
CLERK_FRONTEND_API=${clerk_fapi}
CLERK_WEBHOOK_SECRET=

# App secrets
NEXT_SERVER_ACTIONS_ENCRYPTION_KEY=$(b64key)
AWS_CREDENTIALS_ENCRYPTION_KEY=$(b64key)
AGENT_DISCOVERY_CRON_SECRET=$(openssl rand -hex 32)

# Self-hosted Nango (integrations), served under the app's own origin
NANGO_ENCRYPTION_KEY=$(b64key)
NANGO_SECRET_KEY=$(uuid)
NANGO_HOST=http://nango-server:3003
NANGO_SERVER_URL=${url}/nango-api
NANGO_PUBLIC_SERVER_URL=${url}/nango-api
NANGO_PUBLIC_CONNECT_URL=${url}/nango-connect
NEXT_PUBLIC_NANGO_API_URL=${url}/nango-api
NEXT_PUBLIC_NANGO_CONNECT_URL=${url}/nango-connect
NANGO_DASHBOARD_USERNAME=admin
NANGO_DASHBOARD_PASSWORD=$(openssl rand -hex 12)

# Optional model keys (AI Radar, LLM guards). Add later and run: ./install.sh
OPENAI_API_KEY=
GEMINI_API_KEY=
EOF
  ok ".env written (mode 600). Back it up: losing it loses the keys that encrypt stored credentials."
}

# ── doctor ──────────────────────────────────────────────────────────────────
if [ "${1:-}" = "--doctor" ]; then
  [ -f docker-compose.yml ] || cd "$GOVERNLY_DIR" 2>/dev/null || die "Run this from your Governly folder."
  ok "Governly version $(cat VERSION 2>/dev/null || echo unknown)"
  check_prereqs || true
  [ -f .env ] && ok ".env present" || warn ".env missing: run ./install.sh"
  docker compose -f docker-compose.yml -f deploy/compose.selfhost.yml ps 2>/dev/null || true
  url="$(grep -E '^NEXT_PUBLIC_APP_URL=' .env 2>/dev/null | cut -d= -f2-)"
  curl -fsS "${url:-http://localhost}/healthz" >/dev/null 2>&1 && ok "Governly answers at ${url}" || warn "Governly does not answer at ${url:-http://localhost}/healthz"
  exit 0
fi

# ── install ─────────────────────────────────────────────────────────────────
say "Checking prerequisites"
check_prereqs || die "Fix the items above, then re-run. (Docker: https://docs.docker.com/get-docker/)"

if [ ! -f docker-compose.yml ] || [ ! -f deploy/compose.selfhost.yml ]; then
  if [ -d "$GOVERNLY_DIR/.git" ]; then say "Using existing checkout at $GOVERNLY_DIR"
  else say "Cloning Governly into $GOVERNLY_DIR"; git clone --depth 1 "$GOVERNLY_REPO" "$GOVERNLY_DIR"; fi
  cd "$GOVERNLY_DIR"
fi

default_url="http://localhost"; [ "$GOVERNLY_HTTP_PORT" = 80 ] || default_url="http://localhost:${GOVERNLY_HTTP_PORT}"
GOVERNLY_URL="${GOVERNLY_URL:-$default_url}"; GOVERNLY_URL="${GOVERNLY_URL%/}"
if [ -f .env ]; then ok "Keeping existing .env"; else write_env "$GOVERNLY_URL"; fi

compose() { docker compose -f docker-compose.yml -f deploy/compose.selfhost.yml "$@"; }

say "Building images (first run takes 10-20 minutes)"
compose build
say "Starting the database"
compose up -d --wait postgres
say "Applying database migrations"
compose run --rm migrate
say "Starting Governly"
compose up -d

url="$(grep -E '^NEXT_PUBLIC_APP_URL=' .env | cut -d= -f2-)"
say "Waiting for ${url} to answer"
for _ in $(seq 120); do curl -fsS "${url}/healthz" >/dev/null 2>&1 && break; sleep 5; done
if curl -fsS "${url}/healthz" >/dev/null 2>&1; then
  ok "Governly is running at ${url}"
  cat <<EOF

  Next steps
    1. Open ${url} and sign up. The first organization is created for you.
    2. Clerk: add ${url} to your Clerk app's allowed origins (docs/self-hosting.md#clerk).
    3. Going public? Put HTTPS in front: docs/self-hosting.md#https.

  Status:  ./install.sh --doctor
  Logs:    docker compose -f docker-compose.yml -f deploy/compose.selfhost.yml logs -f web
EOF
else
  warn "Governly did not answer within 10 minutes. Recent web logs:"
  compose logs --tail=40 web || true
  exit 1
fi
